import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const repositoryRoot = fileURLToPath(new URL("../../", import.meta.url));

export const VERSIONS = Object.freeze({
  v3: Object.freeze({
    version: "v3",
    label: "V3",
    schemaRelativePath: "schema/dashboard-api-v3.schema.json",
    typesRelativePath: "src/api/generated/dashboard-v3.ts",
    cargoPackage: "ocg-core",
    cargoExample: "export_dashboard_v3_schema",
    rootTypeName: "DashboardApiV3",
    entryScript: "scripts/dashboard-v3-contract.mjs",
    dtoModule: "dashboard_v3",
    generateScript: "contract:v3:generate",
  }),
  v4: Object.freeze({
    version: "v4",
    label: "V4",
    schemaRelativePath: "schema/dashboard-api-v4.schema.json",
    typesRelativePath: "src/api/generated/dashboard-v4.ts",
    cargoPackage: "ocg-core",
    cargoExample: "export_dashboard_v4_schema",
    rootTypeName: "DashboardApiV4",
    entryScript: "scripts/dashboard-v4-contract.mjs",
    dtoModule: "dashboard_v4",
    generateScript: "contract:v4:generate",
  }),
});

export function resolveContractVersion(version) {
  const spec = VERSIONS[version];
  if (!spec) {
    throw new Error(`Unknown dashboard contract version: ${version}`);
  }
  return spec;
}

export function parseArgs(argv) {
  const flags = argv.filter((arg) => arg !== "--");
  const write = flags.includes("--write");
  const check = flags.includes("--check");
  const unknown = flags.filter((arg) => arg !== "--write" && arg !== "--check");
  if (unknown.length > 0) {
    throw new Error(`Unknown argument(s): ${unknown.join(", ")}`);
  }
  if (write === check) {
    throw new Error("Specify exactly one of --write or --check");
  }
  return write ? "write" : "check";
}

export function normalizeNewlines(text) {
  return String(text ?? "").replaceAll("\r\n", "\n");
}

export function assertTypesAreContractOnly(source) {
  const text = String(source ?? "");
  const forbidden = [
    /\bfetch\s*\(/,
    /\baxios\b/,
    /\bXMLHttpRequest\b/,
    /export\s+async\s+function/,
    /export\s+function\s+\w+\s*\(/,
  ];
  for (const pattern of forbidden) {
    if (pattern.test(text)) {
      throw new Error("generated TypeScript must stay types-only and must never include endpoint clients");
    }
  }
}

export function formatDriftError(spec, driftedPaths) {
  return `Dashboard ${spec.label} contract drifted (${driftedPaths.join(", ")}). Run \`pnpm run ${spec.generateScript}\`.`;
}

function bannerFor(spec) {
  return [
    "/* eslint-disable */",
    "/**",
    ` * AUTO-GENERATED by ${spec.entryScript} from the Rust ${spec.dtoModule} DTOs.`,
    " * Do not edit. Types only; no HTTP wrappers.",
    " */",
    "",
  ].join("\n");
}

function cargoArgsFor(spec) {
  return Object.freeze([
    "run",
    "-p",
    spec.cargoPackage,
    "--example",
    spec.cargoExample,
    "--locked",
    "--quiet",
  ]);
}

export function createDashboardContract(version) {
  const spec = resolveContractVersion(version);
  const SCHEMA_RELATIVE_PATH = spec.schemaRelativePath;
  const TYPES_RELATIVE_PATH = spec.typesRelativePath;
  const ARTIFACT_PATHS = Object.freeze([SCHEMA_RELATIVE_PATH, TYPES_RELATIVE_PATH]);
  const CARGO_EXAMPLE = spec.cargoExample;
  const CARGO_ARGS = cargoArgsFor(spec);
  const banner = bannerFor(spec);

  function assertArtifactsMatch({ generatedSchema, generatedTypes, existingSchema, existingTypes }) {
    const schemaOk = normalizeNewlines(generatedSchema) === normalizeNewlines(existingSchema);
    const typesOk = normalizeNewlines(generatedTypes) === normalizeNewlines(existingTypes);
    if (schemaOk && typesOk) return;
    const drifted = [
      !schemaOk ? SCHEMA_RELATIVE_PATH : null,
      !typesOk ? TYPES_RELATIVE_PATH : null,
    ].filter(Boolean);
    throw new Error(formatDriftError(spec, drifted));
  }

  async function renderTypeScript(schema) {
    const typescript = await compile(schema, spec.rootTypeName, {
      bannerComment: banner,
      additionalProperties: false,
      unreachableDefinitions: true,
      unknownAny: false,
      format: true,
      style: {
        semi: true,
        singleQuote: false,
        trailingComma: "all",
        tabWidth: 2,
      },
    });
    assertTypesAreContractOnly(typescript);
    return normalizeNewlines(typescript).endsWith("\n")
      ? normalizeNewlines(typescript)
      : `${normalizeNewlines(typescript)}\n`;
  }

  function exportSchemaFromCargo({
    spawn = spawnSync,
    cwd = repositoryRoot,
  } = {}) {
    const result = spawn("cargo", [...CARGO_ARGS], {
      cwd,
      encoding: "utf8",
      windowsHide: true,
      env: {
        ...process.env,
        CARGO_TERM_COLOR: "never",
      },
      maxBuffer: 16 * 1024 * 1024,
    });
    if (result.status !== 0) {
      throw new Error(
        `cargo ${CARGO_ARGS.join(" ")} failed:\n${result.stderr || result.stdout || `exit ${result.status}`}`,
      );
    }
    const stdout = result.stdout ?? "";
    const start = stdout.indexOf("{");
    if (start < 0) {
      throw new Error(`cargo ${CARGO_EXAMPLE} did not print a JSON object`);
    }
    const schemaText = normalizeNewlines(stdout.slice(start));
    JSON.parse(schemaText);
    return schemaText.endsWith("\n") ? schemaText : `${schemaText}\n`;
  }

  async function runContract(mode, {
    root = repositoryRoot,
    exportSchema = exportSchemaFromCargo,
    compileSchema = renderTypeScript,
    readText = (path) => readFileSync(path, "utf8"),
    writeText = (path, contents) => {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, contents, "utf8");
    },
  } = {}) {
    if (mode !== "write" && mode !== "check") {
      throw new Error(`Unknown mode: ${mode}`);
    }
    const schemaText = exportSchema();
    const schema = JSON.parse(schemaText);
    const typescript = await compileSchema(schema);
    const schemaPath = join(root, SCHEMA_RELATIVE_PATH);
    const typesPath = join(root, TYPES_RELATIVE_PATH);

    if (mode === "write") {
      writeText(schemaPath, schemaText);
      writeText(typesPath, typescript);
      return { schemaPath, typesPath, wrote: true };
    }

    assertArtifactsMatch({
      generatedSchema: schemaText,
      generatedTypes: typescript,
      existingSchema: readText(schemaPath),
      existingTypes: readText(typesPath),
    });
    return { schemaPath, typesPath, wrote: false };
  }

  return Object.freeze({
    spec,
    banner,
    SCHEMA_RELATIVE_PATH,
    TYPES_RELATIVE_PATH,
    ARTIFACT_PATHS,
    CARGO_EXAMPLE,
    CARGO_ARGS,
    parseArgs,
    normalizeNewlines,
    assertTypesAreContractOnly,
    assertArtifactsMatch,
    renderTypeScript,
    exportSchemaFromCargo,
    runContract,
  });
}

export async function run({ version, argv = process.argv.slice(2), ...deps } = {}) {
  const contract = createDashboardContract(version);
  return contract.runContract(parseArgs(argv), deps);
}
